#!/usr/bin/env python3
"""Regenerates the `KEY_FOLD` table in assets/profiler-engine.js (#939).

Key normalisation (faircode/proxy.py `normalize_key_text`) case-folds with Python's
`str.casefold()`, which does full case folding; JavaScript only has `toLowerCase()`.
The JS engine therefore carries a table of the characters where the two differ (ligatures,
long s, final sigma, sharp s...), applied per character before `toLowerCase()`.

This script rebuilds that table from the Python and node you run it with, over the code
points both runtimes have assigned (the two ship different Unicode versions, and a character
only the newer one knows would otherwise be folded on one side only), and rewrites the block
between the `KEY_FOLD:begin` / `KEY_FOLD:end` markers, stamping the versions used.

    python3 scripts/generate_key_fold.py            # rewrite the table in place
    python3 scripts/generate_key_fold.py --check    # exit 1 if the table folds a character differently from Python
    python3 scripts/generate_key_fold.py --check --require  # fail when node is missing rather than skipping (CI)

`make key-fold` rewrites the table and `make key-fold-check` (also part of `make check` and CI) verifies it:
it compares the engine's normalizeKeyText() with Python's normalize_key_text() for every code point both
runtimes assign, and *says how many it could not compare* because only one runtime knows the character,
so a stale table cannot hide behind the skip (#946). It fails only on a real disagreement and notes when the
running Python or node is newer than the Unicode versions stamped into the table.
"""

from __future__ import annotations

import argparse
import json
import re
import shutil
import subprocess
import sys
import unicodedata
from pathlib import Path

ENGINE = Path(__file__).resolve().parent.parent / "assets" / "profiler-engine.js"
BEGIN, END = "  // KEY_FOLD:begin", "  // KEY_FOLD:end"

NODE_SCRIPT = r"""
const out = {};
const unassigned = /^\p{Cn}$/u;
for (let cp = 0; cp <= 0x10FFFF; cp++) {
  if (cp >= 0xD800 && cp <= 0xDFFF) continue;
  const c = String.fromCodePoint(cp);
  if (!unassigned.test(c)) out[cp] = c.toLowerCase();
}
process.stdout.write(JSON.stringify({ unicode: process.versions.unicode, node: process.version, lower: out }));
"""


def js_escape(text: str) -> str:
    """\\uXXXX escapes (surrogate pairs above the BMP), so the table is plain ASCII."""
    parts = []
    for ch in text:
        cp = ord(ch)
        if cp < 0x10000:
            parts.append("\\u%04x" % cp)
        else:
            cp -= 0x10000
            parts.append("\\u%04x\\u%04x" % (0xD800 + (cp >> 10), 0xDC00 + (cp & 0x3FF)))
    return "".join(parts)


def build_block() -> str:
    done = subprocess.run(["node", "-e", NODE_SCRIPT], capture_output=True, text=True, check=True)
    node = json.loads(done.stdout)
    lower = {int(cp): low for cp, low in node["lower"].items()}
    diffs = {}
    for cp, low in lower.items():
        ch = chr(cp)
        if unicodedata.category(ch) == "Cn":
            continue
        folded = ch.casefold()
        if folded != low:
            diffs[ch] = folded
    items = [f"'{js_escape(k)}':'{js_escape(v)}'" for k, v in diffs.items()]
    lines, cur = [], "   "
    for item in items:
        if len(cur) + len(item) > 110:
            lines.append(cur)
            cur = "   "
        cur += " " + item + ","
    lines.append(cur)
    header = (
        f"{BEGIN}\n"
        f"  // Where Python's casefold() (full case folding) differs from toLowerCase(), per character: the\n"
        f"  // {len(diffs)} characters that fold to something else (ligatures, final sigma, long s, sharp s...).\n"
        f"  // GENERATED by scripts/generate_key_fold.py (make key-fold); do not edit by hand (#911, #939).\n"
        f"  // Built with: Python {sys.version.split()[0]} (Unicode {unicodedata.unidata_version}) and node {node['node']} (Unicode {node['unicode']})\n"
        f"  var KEY_FOLD = {{\n"
    )
    return header + "\n".join(lines) + f"\n  }};\n{END}"


CHECK_NODE_SCRIPT = r"""
require(process.argv[1]);
const E = globalThis.FairCodeProfiler;
const out = [];
const unassigned = /^\p{Cn}$/u;
for (let cp = 0; cp <= 0x10FFFF; cp++) {
  if (cp >= 0xD800 && cp <= 0xDFFF) continue;
  const c = String.fromCodePoint(cp);
  out.push(unassigned.test(c) ? null : E.normalizeKeyText(c));
}
process.stdout.write(JSON.stringify({ unicode: process.versions.unicode, node: process.version, out }));
"""


def _version_tuple(text: str) -> tuple:
    return tuple(int(part) for part in re.findall(r"\d+", text)[:3])


def check_table() -> dict:
    """Compare the engine with Python over every code point both runtimes assign (#946).

    Returns the counts and mismatches; code points assigned in only one runtime are counted as
    skipped rather than silently ignored."""
    from faircode.proxy import normalize_key_text
    done = subprocess.run(["node", "-e", CHECK_NODE_SCRIPT, str(ENGINE)], capture_output=True, text=True, check=True)
    node = json.loads(done.stdout)
    compared = node_only = python_only = 0
    mismatches = []
    index = 0
    for cp in range(0x110000):
        if 0xD800 <= cp <= 0xDFFF:
            continue
        got = node["out"][index]
        index += 1
        py_assigned = unicodedata.category(chr(cp)) != "Cn"
        if got is None and not py_assigned:
            continue
        if got is None:
            python_only += 1
        elif not py_assigned:
            node_only += 1
        else:
            compared += 1
            if got != normalize_key_text(chr(cp)):
                mismatches.append(cp)
    stamp = re.search(r"Built with: Python (\S+) \(Unicode (\S+)\) and node (\S+) \(Unicode (\S+)\)",
                      ENGINE.read_text(encoding="utf-8"))
    return {"compared": compared, "node_only": node_only, "python_only": python_only, "mismatches": mismatches,
            "node": node, "built_with": stamp.groups() if stamp else None}


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    parser.add_argument("--check", action="store_true", help="exit 1 if the table is out of date; write nothing")
    parser.add_argument("--require", action="store_true", help="fail when node is missing rather than skipping the check")
    args = parser.parse_args(argv)
    source = ENGINE.read_text(encoding="utf-8")
    start, stop = source.find(BEGIN), source.find(END)
    if start == -1 or stop == -1:
        print(f"error: KEY_FOLD markers not found in {ENGINE}", file=sys.stderr)
        return 2
    stop += len(END)
    if args.check:
        if shutil.which("node") is None:
            print("node is needed for this check (install Node 18+); skipping")
            return 2 if args.require else 0
        r = check_table()
        print(f"Python {sys.version.split()[0]} (Unicode {unicodedata.unidata_version}), node {r['node']['node']} "
              f"(Unicode {r['node']['unicode']})")
        if r["built_with"]:
            py_v, py_u, node_v, node_u = r["built_with"]
            print(f"table built with Python {py_v} (Unicode {py_u}), node {node_v} (Unicode {node_u})")
            if (_version_tuple(unicodedata.unidata_version) > _version_tuple(py_u)
                    or _version_tuple(r["node"]["unicode"]) > _version_tuple(node_u)):
                print("note: this Python or node knows a newer Unicode than the table was built with; "
                      "run `make key-fold` to refresh it")
        print(f"compared {r['compared']:,} code points; not compared: {r['node_only']:,} assigned only in node, "
              f"{r['python_only']:,} only in Python")
        if r["mismatches"]:
            shown = ", ".join(f"U+{cp:04X}" for cp in r["mismatches"][:10])
            print(f"KEY_FOLD is STALE: {len(r['mismatches']):,} code point(s) fold differently from Python ({shown}"
                  f"{'...' if len(r['mismatches']) > 10 else ''}) - run: make key-fold")
            return 1
        print("KEY_FOLD agrees with Python on every code point both runtimes assign")
        return 0
    block = build_block()
    ENGINE.write_text(source[:start] + block + source[stop:], encoding="utf-8")
    print(f"KEY_FOLD rewritten ({block.count(chr(39) + ':' + chr(39))} entries)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
